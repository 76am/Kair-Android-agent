package dev.kair.app.ui.plugins.builtin

/**
 * 记忆段的固定文案与两张整理 prompt（只有这里允许出现面向模型的中文）。
 *
 * 为什么固定文案必须**恒定**：它进入系统提示的缓存稳定前缀（`PromptSectionCache` 契约）。
 * 段内不得出现「当天日期」或随回合变化的计数；[maintenance] 里唯一可变的只有上限值 N，
 * 那由用户设置驱动、低频变化，可以接受。条数类标注（截断 / 格式不合法 / 回滚）只在
 * 对应情形出现，且全部由文件内容与设置决定 —— 同一输入两次渲染逐字节相等。
 */
object MemoryPrompts {

    /** 段标题（沿用外部插件时期的模型可见标题，减少行为漂移）。 */
    const val SECTION_TITLE = "## 跨会话记忆"

    /** 文件与注入段共用的两个 H2 段标题（文件格式的唯一声明处）。 */
    const val STABLE_HEADER = "## 稳定"
    const val RECENT_HEADER = "## 近期"

    /** 空文件时的占位：让模型知道有这个通道，而不是以为整段不存在。 */
    const val EMPTY_NOTE = "（当前无记忆）"

    /**
     * 新项目的记忆文件模板：只给两段标题，不写任何条目。
     *
     * 注入时仍是「（当前无记忆）」——模板只是给面板编辑器与 read 工具一个明确落点，
     * 不改变渲染字节（缓存前缀不受影响）。
     */
    const val TEMPLATE = "## 稳定\n\n## 近期\n"

    /**
     * 段尾维护规则（不是记忆内容）。位置在段内尾部而不是整个系统提示的最末：
     * 模型读完条目紧接着就是它。**不含当天日期** —— 那会让缓存前缀每回合失效。
     *
     * 文件位置与格式必须写在这里：这是主 agent 唯一能看到「记忆在哪、长什么样」的地方。
     * 只写工作区相对路径 `<workspace>/.kair/memory.md`（`container_shell` 的 cwd 即工作区根），
     * 不写宿主绝对路径 —— 后者每个项目都不同，写进段落会白白拉长缓存前缀。
     */
    fun maintenance(maxChars: Int): String =
        "维护规则（不是记忆内容）：记忆文件是工作区里的 `.kair/memory.md`（相对工作区根，不存在就新建），" +
            "用 read / write / edit 读写；" +
            "格式固定为 `## 稳定` 与 `## 近期` 两段，每条一行 `- YYYY-MM-DD: 事实`，≤ 60 字；" +
            "写「现在是什么 / 在哪 / 怎么做」，不写「我改了什么」；稳定段放长期不变的约定，" +
            "近期段放状态与进度，过期自动不再注入。本段上限 $maxChars 字，超出从尾部截断。"

    /** 预算截断的段尾标注；[n] 必须等于实际丢弃条数。 */
    fun omitted(n: Int): String = "另有 $n 条未注入"

    /** 缺日期前缀的行：仍然注入（不丢信息），但点名让整理收拾。 */
    fun invalid(n: Int): String =
        "另有 $n 条格式不合法（缺少 `- YYYY-MM-DD: ` 前缀），请在下一次整理时修正"

    /** 单行超过 200 字（§4.6 的应用侧守卫：不拒写、不自动改写，只点名）。 */
    fun overlong(lines: List<Int>): String {
        val where = lines.joinToString("、") { "第 $it 行" }
        return "$where 超过 200 字，请在下一次整理时压缩"
    }

    /** 整理结果没变短、已回滚：写进下一次注入的维护块末尾。 */
    fun rolledBack(): String = "上次整理未变短，已回滚"

    /**
     * 播种 prompt（文件为空时）：只让子智能体写入、**不要**它把正文回灌给宿主。
     *
     * [path] 是宿主绝对路径：子智能体用 read / write / edit 直接改文件；`container_shell`
     * 里没有这个宿主路径（容器只挂 /projects），必须写清楚。
     */
    fun appendPrompt(path: String, digest: String, today: String): String = """
        你在维护 Kair 的跨会话记忆文件。用 read / write / edit 工具直接修改这个宿主绝对路径：
        $path

        不要使用 container_shell（宿主绝对路径在容器里不存在），也不要动工作区里的其他文件。
        当前文件为空，请从下面的回合摘录里挑出值得跨会话保留的事实写进去。

        回合摘录：
        $digest

        写入格式（文件里就用这两个标题，每条一行）：
        ## 稳定
        - YYYY-MM-DD: 事实

        ## 近期
        - YYYY-MM-DD: 事实

        规则：
        - 日期用事实发生的日期；今天是 $today。
        - 每条 ≤ 60 字；写「现在是什么 / 在哪 / 怎么做」，不写「我改了什么」。
        - 稳定段：偏好、约定、硬约束、命令、路径契约、踩过的坑；近期段：进度、状态、版本号、待办、当前分支。
        - 没有值得写的内容就不要创建文件。
        - 完成后只回复 done，不要在回复里粘贴记忆正文。
    """.trimIndent()

    /**
     * 合并 prompt（文件已有内容）：要求整份重写并**严格变短**。
     *
     * 同样只让子智能体用它自己的文件工具改文件；宿主在它返回后读文件校验，绝不把返回值
     * 当正文覆盖写（返回值只用于判失败）。
     */
    fun mergePrompt(path: String, current: String, digest: String, today: String): String = """
        你在整理 Kair 的跨会话记忆文件。用 read 读出当前内容，再用 write / edit 把同一个宿主绝对路径改短：
        $path

        不要使用 container_shell（宿主绝对路径在容器里不存在），也不要动工作区里的其他文件。

        当前内容：
        $current

        自上次整理以来的回合摘录：
        $digest

        规则：
        - 改完的文件必须比当前内容更短（字符数严格下降）；做不到就只做删除 / 合并，不要新增。
        - 保留所有仍然有效的稳定条目，一条都不能丢；已经长期不再变化的近期条目升级到稳定段。
        - 合并重复 / 同义条目；删掉确实过期的近期条目，只保留最近 30 天内的状态。
        - 每条 ≤ 60 字；数字、路径、命令、否定条件不许省；语义不变才压。
        - 每条仍写成 `- YYYY-MM-DD: 事实`，日期沿用事实发生的日期；今天是 $today。
        - 文件只保留 `## 稳定` / `## 近期` 两段，不要加别的标题。
        - 完成后只回复 done，不要在回复里粘贴记忆正文。
    """.trimIndent()
}
