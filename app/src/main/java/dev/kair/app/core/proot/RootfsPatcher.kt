package dev.kair.app.core.proot

import java.io.File

/**
 * rootfs 落盘后的适配补丁。Ubuntu base 是「纯净」发行版镜像，直接跑在 Android + proot
 * 上有几处水土不服，安装时一次性补齐：
 *
 * - `/etc/resolv.conf`：DNS。Android 侧拿不到系统解析器配置，写公共递归（国内优先）；
 * - `/etc/hosts`：localhost 反解析，部分程序（如 python socket）依赖；
 * - `/etc/group`：补常见 Android GID 映射，`ls -l` 不至于显示裸数字；
 * - `tmp` / `var/tmp` / `root` / `root/.cache`：确保存在且可写（root 以 uid 0 运行；
 *   `~/.cache` 缺失会让 gvfs 的 peer-to-peer 连接刷警告）；
 * - `/etc/apt/sources.list` + `/etc/apt/apt.conf.d/99kair`：apt 走所选镜像，且
 *   **首轮用 http**（base 镜像不带 CA 证书）；`APT::Sandbox::User "root"` 解决 proot 下
 *   `_apt` 降权问题；`Acquire::Languages "none"` 省掉约 10 MB 索引；
 * - `/usr/sbin/policy-rc.d`：返回 101，阻止包 postinst 在容器里尝试起系统服务；
 * - `/etc/pip.conf`：pip 走所选镜像。
 */
internal object RootfsPatcher {

    /** 公共 DNS：国内（阿里 / 腾讯）在前，谷歌兜底海外场景。 */
    private val DNS_SERVERS = listOf("223.5.5.5", "119.29.29.29", "8.8.8.8")

    /** bind 场景下最可能出现的 Android 补充 GID（仅命名，无功能影响）。 */
    private val ANDROID_GIDS = listOf(
        9997 to "android_everybody",
        1015 to "android_sdcard",
        1023 to "android_media_rw",
    )

    fun patch(rootfs: File, mirror: ContainerMirror, arch: String) {
        writeResolvConf(rootfs)
        writeHosts(rootfs)
        patchGroup(rootfs)
        ensureDirs(rootfs)
        applyMirror(rootfs, mirror, arch)
    }

    /**
     * 只写包管理器镜像（安装补丁与「已装 rootfs 切源」共用一处实现）。
     *
     * **覆盖写** sources.list：base 镜像自带的是 `archive.ubuntu.com`（arm64 上是
     * `ports.ubuntu.com`），按行替换会静默漏掉某个 pocket；换源后清 apt lists，
     * 否则旧索引会残留。
     */
    fun applyMirror(rootfs: File, mirror: ContainerMirror, arch: String) {
        writeAptSources(rootfs, mirror.aptBase(arch))
        writeAptConf(rootfs)
        writePolicyRcD(rootfs)
        writePipConf(rootfs, mirror.pipIndex)
        clearAptLists(rootfs)
    }

    private fun writeAptSources(rootfs: File, aptBase: String) {
        // 版本号只从 RootfsManager 取一处，避免第二份硬编码跟着升级漂移。
        val release = RootfsManager.UBUNTU_RELEASE
        val content = buildString {
            appendLine("deb $aptBase $release main restricted universe")
            appendLine("deb $aptBase $release-updates main restricted universe")
            appendLine("deb $aptBase $release-security main restricted universe")
        }
        File(rootfs, "etc/apt/sources.list").apply { parentFile?.mkdirs() }.writeText(content)
    }

    private fun writeAptConf(rootfs: File) {
        val content = buildString {
            appendLine("APT::Sandbox::User \"root\";")
            appendLine("Acquire::Languages \"none\";")
            appendLine("Acquire::Retries \"3\";")
            appendLine("DPkg::Options { \"--force-confdef\"; \"--force-confold\"; };")
        }
        File(rootfs, "etc/apt/apt.conf.d/99kair").apply { parentFile?.mkdirs() }.writeText(content)
    }

    /**
     * 容器里没有 systemd / init；包 postinst 若尝试起服务会卡住或报错。
     * 标准容器做法：policy-rc.d 返回 101，`invoke-rc.d` 直接跳过。
     */
    private fun writePolicyRcD(rootfs: File) {
        val file = File(rootfs, "usr/sbin/policy-rc.d")
        file.parentFile?.mkdirs()
        file.writeText("#!/bin/sh\n# Kair: packages must not start system services inside proot.\nexit 101\n")
        file.setExecutable(true, false)
    }

    private fun writePipConf(rootfs: File, indexUrl: String) {
        // 选项名是单数 disable-（写成 disables- 时 pip 只打一条 unknown option 警告、功能照跑）。
        val content = buildString {
            appendLine("[global]")
            appendLine("index-url = $indexUrl")
            appendLine("disable-pip-version-check = true")
        }
        File(rootfs, "etc/pip.conf").apply { parentFile?.mkdirs() }.writeText(content)
    }

    private fun clearAptLists(rootfs: File) {
        val dir = File(rootfs, "var/lib/apt/lists")
        if (!dir.isDirectory) {
            dir.mkdirs()
            return
        }
        dir.listFiles()?.forEach { it.deleteRecursively() }
    }

    private fun writeResolvConf(rootfs: File) {
        val content = buildString {
            appendLine("# Generated by Kair; edit freely, reinstall resets it.")
            DNS_SERVERS.forEach { appendLine("nameserver $it") }
        }
        File(rootfs, "etc/resolv.conf").apply { parentFile?.mkdirs() }.writeText(content)
    }

    private fun writeHosts(rootfs: File) {
        val content = """
            127.0.0.1 localhost
            ::1 localhost
        """.trimIndent() + "\n"
        File(rootfs, "etc/hosts").apply { parentFile?.mkdirs() }.writeText(content)
    }

    private fun patchGroup(rootfs: File) {
        val group = File(rootfs, "etc/group")
        if (!group.exists()) return // 非预期发行版布局，不动
        val existing = group.readText()
        val additions = ANDROID_GIDS.filterNot { (gid, _) ->
            existing.lineSequence().any { line -> line.split(':').getOrNull(2) == gid.toString() }
        }.joinToString("") { (gid, name) -> "$name:x:$gid:\n" }
        if (additions.isNotEmpty()) group.appendText(additions)
    }

    private fun ensureDirs(rootfs: File) {
        File(rootfs, "tmp").apply { mkdirs() }.setWritable(true, false)
        File(rootfs, "var/tmp").apply { mkdirs() }.setWritable(true, false)
        File(rootfs, "root").apply { mkdirs() }
        // gvfs 的 peer-to-peer 连接按 $HOME/.cache/gvfsd 找 socket；目录不存在会刷警告。
        File(rootfs, "root/.cache").apply { mkdirs() }
    }
}
