package dev.kair.app.core.proot

/**
 * 容器内循环脚本（POSIX sh，busybox ash 可跑）：
 * 回显就绪帧 → 逐行读命令 → `eval`（**在主 shell 里**，所以 `cd` / 变量跨命令保留，
 * 这是「像真电脑」的关键）→ 回显退出帧。
 *
 * 命令经 `</dev/null` 执行：否则命令会吃掉宿主的命令流（例如 `cat` / 交互式解释器）。
 */
internal fun sessionEntryScript(): String = buildString {
    appendLine("#!/bin/sh")
    appendLine("# Kair persistent session loop (generated by the host; frame protocol in ContainerSession).")
    // 与一次性命令同一约定：root 新建的文件对 App 可读写（见 RootCommandRunner.buildScript）。
    appendLine("umask 000")
    // 起始目录 = 全部项目的父目录；一个项目都没挂时它不存在，退回 `/`。
    appendLine("cd $PROJECTS_ROOT 2>/dev/null || cd /")
    appendLine("printf '%s\\n' '${ContainerSession.READY_TOKEN}'")
    appendLine("while IFS= read -r __kair_line; do")
    appendLine("  if [ \"\$__kair_line\" = '${ContainerSession.STOP_TOKEN}' ]; then break; fi")
    appendLine("  eval \"\$__kair_line\" </dev/null")
    appendLine("  printf '%s%s%s\\n' '${ContainerSession.RC_PREFIX}' \"\$?\" '${ContainerSession.RC_SUFFIX}'")
    appendLine("done")
    appendLine("exit 0")
}
